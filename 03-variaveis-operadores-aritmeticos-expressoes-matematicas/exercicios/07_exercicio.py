"""
Exercício 7: prevendo o resultado de expressões

Calcule as expressões abaixo mentalmente, anotando os resultados.
Depois execute a célula para conferir.

a) 2 + 3 * 4, b) (2 + 3) * 4, c) 2 ** 3 + 1, d) 2 ** (3 + 1)
e) 10 - 4 / 2, f) (10 - 4) / 2, g) 10 / 2 * 3, h) 10 / (2 * 3)
"""

# 2 + 12 = 14
print(f"a) {2} + {3} * {4} = {2 + 3 * 4}")

# (2 + 3) * 4 = 5 * 4 = 20
print(f"b) ({2} + {3}) * {4} = {(2 + 3) * 4}")

# 2 ** 3 + 1 = 8 + 1 = 9
print(f"c) {2} ** {3} + {1} = {2 ** 3 + 1}")

# 2 ** (3 + 1) = 2 ** 4 = 16
print(f"d) {2} ** ({3} + {1}) = {2 ** (3 + 1)}")

# 10 - 4 / 2 = 10 - 2 = 8.0
print(f"e) {10} - {4} / {2} = {10 - 4 / 2}")

# (10 - 4) / 2 = 6 / 2 = 3.0
print(f"f) ({10} - {4}) / {2} = {(10 - 4) / 2}")

# 10 / 2 * 3 = 5.0 * 3 = 15.0
print(f"g) {10} / {2} * {3} = {10 / 2 * 3}")

# 10 / (2 * 3) = 10 / (6) = 10 / 6 = 5 / 3 = 1.67
print(f"h) {10} / ({2} * {3}) = {10 / (2 * 3)}")