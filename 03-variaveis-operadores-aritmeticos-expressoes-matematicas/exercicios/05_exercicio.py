"""
Exercício 5: prevendo tipos

Antes de executar, escreva em um comentário qual tipo você acha que cada valor
abaixo tem. Depois use print(type(...)) para conferir.

Valores:

a) 7, b) "7", c) 7.0, d) "sete", e) True, f) "True"
"""

print(f"a) {7} => {type(7)}") # 7 => int (inteiro)
print(f"b) {'7'} => {type('7')}") # '7' => str (texto)
print(f"c) {7.0} => {type(7.0)}") # 7.0 => float (decimal)
print(f"d) {'sete'} => {type('sete')}") # 'sete' => str (texto)
print(f"e) {True} => {type(True)}") # True => bool (booleano)
print(f"f) {'True'} => {type('True')}") # 'True' => bool (booleano)